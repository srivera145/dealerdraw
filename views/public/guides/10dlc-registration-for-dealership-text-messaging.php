<h1>10DLC registration for dealership text messaging</h1>

<p class="lede">
    10DLC is the system US mobile carriers use to identify legitimate business text messaging sent from ordinary
    ten-digit phone numbers. A dealership that sends application-to-person messages without registering will find
    its messages filtered or blocked outright, usually with no error and no warning. Registration is a
    prerequisite for text messaging working at all, not an optional compliance nicety.
</p>

<h2>What does 10DLC actually mean?</h2>

<p>
    10DLC stands for 10-digit long code, meaning a standard local phone number used to send business messages at
    scale. Carriers built the registration system to separate legitimate business traffic from spam, because
    before it existed the only signal they had was volume. Registering associates your business identity and your
    messaging use case with the number you send from.
</p>

<p>
    It applies to application-to-person traffic - messages sent by software rather than typed by a person on a
    handset. A dealership sending appointment reminders, service updates or promotional offers from a platform is
    sending A2P traffic, even if the number looks like an ordinary local line.
</p>

<h2>What happens if a dealership skips registration?</h2>

<p>
    Unregistered A2P traffic gets filtered, and the failure is usually silent. Your platform reports the message
    as sent, the carrier drops it, and the customer never sees it. Nobody gets an error, so the problem often
    goes unnoticed for weeks while the store concludes that texting does not work for them.
</p>

<p>
    This is the single most common reason a dealership's messaging programme underperforms without an obvious
    cause. If your delivery reports look healthy but your response rate is near zero, registration status is the
    first thing to check.
</p>

<h2>What is the order of operations?</h2>

<p>
    Registration happens in two stages: brand registration, then campaign registration. The brand is your
    business - legal name, tax ID, address, contact. The campaign is the specific use case you intend to send,
    with sample messages and a description of how you collect consent. You cannot register a campaign without a
    brand.
</p>

<p>
    Practically, your messaging provider or platform submits both on your behalf through a registry. What they
    need from you is accurate business information - and it must match your official records exactly. A legal
    name that differs from your tax registration by a word is one of the most common causes of a rejected or
    poorly-scored brand.
</p>

<h2>What is a trust score and why does it matter?</h2>

<p>
    Brands are assigned a score based on the completeness and verifiability of the information supplied, and that
    score determines how many messages per minute you are permitted to send. A low score does not stop you
    messaging, but it throttles throughput, which matters if you ever want to send to a large segment at once.
</p>

<p>
    You improve it by supplying accurate, verifiable business details rather than by asking for a review. An
    established business with a matching tax ID, a real website and consistent contact information generally
    scores well. Vague campaign descriptions and thin sample messages generally do not.
</p>

<h2>What does the consent description need to say?</h2>

<p>
    Your campaign registration has to describe how customers opt in, and that description has to match what you
    actually do. If you say consent is collected through a checkbox on a web form, that form needs to exist and
    the checkbox needs to be there, unticked, with the disclosure next to it. Reviewers do check.
</p>

<p>
    Have a screenshot of the actual opt-in ready, along with the exact wording next to the checkbox. The wording
    should name your dealership, say what kind of messages will be sent and roughly how often, state that message
    and data rates may apply, and explain how to stop. Consent must not be a condition of buying anything.
</p>

<h2>What do the messages themselves need to include?</h2>

<p>
    Every promotional message should identify your dealership by name and tell the recipient how to opt out. The
    first message someone receives after opting in should also make the programme clear. Keep the opt-out
    instruction on the message itself rather than assuming the recipient knows to reply STOP.
</p>

<p>
    Handle STOP, and its common variants, automatically and immediately. Handle HELP with a reply that names your
    business and gives a contact. An opt-out should apply across everything you send that person, not just the
    campaign they happened to reply to - a customer who stops one promotion and keeps receiving another from the
    same dealership is the complaint that costs you.
</p>

<h2>How does 10DLC relate to the TCPA?</h2>

<p>
    They are separate obligations that people routinely confuse. 10DLC is a carrier requirement about
    deliverability, enforced by the networks. The TCPA is federal law about consent, enforced by regulators and
    private lawsuits. Registering for 10DLC does not give you consent, and having consent does not get your
    messages delivered.
</p>

<p>
    You need both. The expensive one is the TCPA, because statutory damages are per message and class actions
    are routine. The one that quietly wastes your budget is 10DLC, because unregistered traffic disappears while
    you keep paying to send it.
</p>

<h2>What should a dealership actually do first?</h2>

<p>
    Start with consent capture, because everything downstream depends on it. Get a real opt-in mechanism in
    place, with stored records of who agreed to what and when, before you register a campaign describing it.
    Then register the brand, then the campaign, then start sending.
</p>

<p>
    Doing it in the other order is how stores end up describing a consent process they have not built, getting a
    campaign rejected, and losing weeks. It also means that when the campaign is approved, you have a list you
    can legitimately message on day one rather than an empty one.
</p>

<h2>The short version</h2>

<p>
    Register the brand, register the campaign, describe your real consent mechanism accurately, put your
    dealership's name and an opt-out on every message, and honour opt-outs across everything. Fees, review times
    and score mechanics vary by provider and change over time, so get current figures from whoever is sending
    your traffic rather than from an article. What does not change is that unregistered messages quietly go
    nowhere.
</p>

<p>
    This is a description of how the system works, not legal advice. Your own counsel should review your consent
    language and your messaging practices before you send at scale.
</p>
