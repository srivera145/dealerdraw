<h1>Free-entry promotions vs sweepstakes vs lottery</h1>

<p class="lede">
    The difference between a lottery, a sweepstakes and a contest comes down to three elements: prize, chance and
    consideration. A lottery has all three and is illegal for a private business to run in most US states. Remove
    consideration and you have a sweepstakes; replace chance with skill and you have a contest.
</p>

<h2>What are the three elements?</h2>

<p>
    Prize is something of value the winner receives. Chance means the outcome is determined by something the
    entrant does not control. Consideration is what the entrant gives up to take part - normally money or a
    purchase. All three together make a lottery, which in the United States is generally reserved to the states
    themselves and licensed operators.
</p>

<p>
    The test is conjunctive, which is the part people miss. You do not reduce your risk by making a lottery
    smaller or more charitable. You change its legal character by removing one of the three elements entirely.
</p>

<h2>What is a sweepstakes?</h2>

<p>
    A sweepstakes is a promotion with a prize awarded by chance where entrants give no consideration. It is the
    structure behind essentially every consumer giveaway you have seen, which is why "no purchase necessary"
    appears on all of them. The winner is still picked at random - that part is unchanged.
</p>

<p>
    Because entry is free, a sweepstakes can be run by an ordinary business without a gaming licence. What can
    still apply is state registration above certain prize-value thresholds, and general rules about advertising
    honestly and delivering the prizes you promised.
</p>

<h2>What is a contest?</h2>

<p>
    A contest awards a prize based on skill rather than chance - a photo competition judged on criteria, for
    instance. Because chance has been removed rather than consideration, a contest can sometimes charge an entry
    fee. The trade-off is that judging has to be genuine, with published criteria and real evaluation.
</p>

<p>
    For most dealerships this is more trouble than it is worth. A skill contest needs judges, criteria, a tie-break
    procedure and a defensible record of how decisions were made. A free-entry sweepstakes needs none of that.
</p>

<h2>What counts as consideration?</h2>

<p>
    Consideration is clearest when it is money - an entry fee, a ticket price, a donation. It also covers
    requiring a purchase, and it can extend to requiring a qualifying transaction such as booking a service or
    taking a test drive. A minority of states have historically read it more broadly to include substantial time
    or effort.
</p>

<p>
    Things generally not treated as consideration: filling in a short entry form, providing your name and contact
    details, visiting a website, or agreeing to receive marketing. That last one is worth stating plainly - asking
    for marketing consent as part of a free entry is standard practice, though the consent itself has to meet the
    separate requirements that govern email and text messaging.
</p>

<h2>Where do dealerships usually get this wrong?</h2>

<p>
    The common failure is reintroducing consideration for a commercial reason after the promotion is designed.
    Restricting entry to customers with an open repair order, awarding extra entries for a purchase, or asking for
    a "suggested donation" all put the third element back. The board looks the same and the legal character has
    changed completely.
</p>

<p>
    The second failure is printing "no purchase necessary" on something where a purchase is, in practice,
    necessary. If the only realistic route to entry runs through the service department, the disclaimer does not
    save you. An alternative free entry method has to be genuinely available and reasonably equivalent, not
    buried in a way designed to be missed.
</p>

<h2>Does it matter that the prize is small?</h2>

<p>
    Prize size does not change whether a promotion is a lottery. A pool for a $50 prize funded by $5 entries has
    the same three elements as one for $50,000. What prize size does affect is state registration thresholds,
    which is a separate question that only arises once you are already running a lawful sweepstakes.
</p>

<p>
    It also affects practical risk, which is not the same as legality. Enforcement attention scales with
    visibility and money involved. That is a poor foundation for a promotion your dealership advertises under its
    own name to the public.
</p>

<h2>Where does a free dealership game board land?</h2>

<p>
    A dealership game board where anyone can claim a square at no cost, with no purchase required, is a
    sweepstakes. It has a prize and it has chance, but the entrant gives up nothing but their contact details.
    That structure is legal for a private business to run in most states, subject to the registration thresholds
    that apply above certain prize values.
</p>

<p>
    Keeping it there is an operational discipline rather than a one-time decision. Entry stays free for everyone,
    for the whole run of the promotion, with no tier of entrant who gets more squares for spending money. The
    rules say so on the entry page, and the entry page collects no payment details of any kind.
</p>

<h2>Quick reference</h2>

<ul>
    <li><strong>Lottery:</strong> prize + chance + consideration. Illegal for private businesses in most states.</li>
    <li><strong>Sweepstakes:</strong> prize + chance, no consideration. Legal, may require registration above certain prize values.</li>
    <li><strong>Contest:</strong> prize + skill. May charge entry, but requires genuine judging.</li>
</ul>

<p>
    Sweepstakes law is state-specific and changes. This is the framework, not legal advice - have your own
    counsel confirm the position for every state you operate in before you launch.
</p>
