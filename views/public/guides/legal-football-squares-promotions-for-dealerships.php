<h1>How dealerships run legal football squares promotions</h1>

<p class="lede">
    A dealership can run a football squares board legally in most US states by making entry free. The office pool
    version is illegal in most states because everyone pays into a pot, which supplies the third element of a
    lottery. Remove the payment and you have a sweepstakes, which is a normal, well-established form of promotion.
</p>

<h2>What makes a squares pool illegal in the first place?</h2>

<p>
    A promotion is an illegal lottery when it contains three elements at once: a prize, an element of chance, and
    consideration given by the entrant. A traditional squares pool has all three, because players pay for squares,
    the digits are drawn at random, and the pot goes to the winner. That is the definition of a lottery in most
    states, and it is illegal to run one privately regardless of how small the stakes are or how well-intentioned
    the organiser is.
</p>

<p>
    People are often surprised by this because office pools are so common. Common is not the same as legal. The
    reason nobody gets prosecuted for a $5 pool in a break room is prosecutorial discretion, not a legal
    exemption - and a franchised dealership running a public promotion under its own name is a very different
    risk profile from four colleagues and a spreadsheet.
</p>

<h2>How does making entry free change the analysis?</h2>

<p>
    Removing the entry fee removes consideration, which leaves only prize and chance - and prize plus chance
    without consideration is a sweepstakes, not a lottery. This is the same structure behind every "no purchase
    necessary" giveaway you have ever seen on a soft drink can. The mechanic on the board does not change at all;
    what changes is that nobody paid to be on it.
</p>

<p>
    That is why the phrase "no purchase necessary" appears on legitimate promotions. It is not decorative
    language. It is the operator documenting that the consideration element has been removed, and it has to be
    literally true.
</p>

<h2>What counts as consideration besides money?</h2>

<p>
    Consideration is usually money or a purchase, but requiring a customer to buy a service, book an appointment,
    or make a qualifying transaction to enter can also be treated as consideration. A handful of states have
    historically read consideration more broadly to include significant time or effort. The safe position is to
    ask for nothing beyond the entrant's contact details.
</p>

<p>
    Practical translation for a service drive: do not restrict entry to customers with an open repair order, do
    not require a test drive, and do not make squares a thank-you for spending a certain amount. Any of those
    turns a clean sweepstakes into an argument you do not want to have. If you want to reward paying customers,
    do it with something other than the entry itself.
</p>

<h2>Do prizes have to be non-cash?</h2>

<p>
    Prizes do not legally have to be non-cash in a sweepstakes, but for a dealership there are good reasons to
    keep them as service offers. A service offer costs you internal parts and labour rather than cash, it has a
    clear retail value you can print on the rules, and redeeming it brings the winner back into your building.
    Cash prizes also make the promotion look far more like gambling to anyone glancing at it.
</p>

<p>
    Give the offer a stated retail value and an expiry, and state plainly that it has no cash value and cannot be
    exchanged. That is ordinary promotional hygiene and it removes ambiguity for the advisor at the counter.
</p>

<h2>What do the official rules need to say?</h2>

<p>
    Your rules need to state who can enter, how to enter for free, the start and end dates, how winners are
    determined, what the prizes are and their retail value, how winners are notified, and who is running the
    promotion. They should be published on the same page as the entry form, not behind a link nobody clicks.
    Keep them short enough that a customer might actually read them.
</p>

<p>
    Include the sponsor's legal name and address, an eligibility statement (typically legal residents of your
    state, over 18), and a line covering what happens if a prize goes unclaimed. If your board is tied to a
    professional or college game, avoid implying that the league, the teams or the broadcaster is involved in
    any way - they are not, and suggesting otherwise creates a trademark problem on top of everything else.
</p>

<h2>Does a dealership need to register a sweepstakes?</h2>

<p>
    Most free-entry dealership promotions fall below the thresholds that trigger state sweepstakes registration.
    Florida and New York have historically required registration and a bond for promotions with a total prize
    value above $5,000, and Rhode Island has required registration for retail sweepstakes above $500. A board
    giving away routine service offers is usually well under the first two figures.
</p>

<p>
    Add up the retail value of every prize on the board, not the cost to you, and compare that total against the
    states you operate in. If you run several boards across a season, ask your counsel whether they are treated
    as separate promotions or one. Thresholds and filing windows change, so confirm the current position rather
    than relying on a number quoted on a vendor's website - including this one.
</p>

<h2>How do you keep the record straight afterwards?</h2>

<p>
    Keep a record of who entered, when, what they consented to, and how the winning squares were determined.
    If a question ever comes up - from a customer, a regulator, or your own compliance officer - the answer
    should be a stored record rather than somebody's memory of a Sunday afternoon.
</p>

<p>
    That means the digits should be assigned by a documented random process after entries close, not chosen by
    a manager, and the assignment should be timestamped. It means consent should be captured as an explicit,
    unticked checkbox with the wording stored alongside it. And it means the winner notification, the redemption
    code and the moment an advisor marked it used should all be retrievable months later.
</p>

<h2>The short version</h2>

<p>
    Make entry genuinely free, keep prizes to service offers with stated retail values, publish real rules on
    the entry page, assign the numbers randomly after entries close, and keep the records. That is the whole
    operational picture. The legal framework is well settled; almost every problem in this area comes from an
    operator quietly reintroducing consideration because it felt like a good way to drive traffic.
</p>

<p>
    None of this is legal advice, and sweepstakes law is state-specific. Have your own counsel review your rules
    before your first board goes live - it is a short review, and it is much cheaper than the alternative.
</p>
